/**
 * Intermediate Allure 3 report theme (after generate, before notifications).
 * Palette A from @allure-notifications/pyramid — colors-only, no SVG reshape.
 */
import fs from "node:fs";
import path from "node:path";

import {
  LAYER_ORDER,
  OTHER_LAYER,
  PYRAMID_COLORS_DARK,
  PYRAMID_COLORS_LIGHT,
} from "@allure-notifications/pyramid";

const TARGETS = ["awesome/index.html", "dashboard/index.html"];
const CSS_NAME = "an-dashboard-theme.css";
const JS_NAME = "an-dashboard-theme.js";
const DATA_ATTR = "data-an-dashboard-theme";

/**
 * @param {{ reportRoot: string }} opts
 */
export function applyDashboardTheme({ reportRoot }) {
  fs.mkdirSync(reportRoot, { recursive: true });
  fs.writeFileSync(path.join(reportRoot, CSS_NAME), buildThemeCss(), "utf8");
  fs.writeFileSync(path.join(reportRoot, JS_NAME), buildThemeJs(), "utf8");

  for (const rel of TARGETS) {
    patchHtmlFile({
      filePath: path.join(reportRoot, rel),
      cssHref: `../${CSS_NAME}`,
      jsHref: `../${JS_NAME}`,
    });
  }
}

function buildThemeCss() {
  const light = cssVarsBlock(PYRAMID_COLORS_LIGHT);
  const dark = cssVarsBlock(PYRAMID_COLORS_DARK);
  return `/* Generated by zds dashboardTheme from @allure-notifications/pyramid.
 * Intermediate step: allure generate → theme → notifications.
 * Colors only — no geometry rewrite.
 */
:root {
  color-scheme: light;
${light}
}

html[data-theme="light"] {
  color-scheme: light;
${light}
}

html[data-theme="dark"] {
  color-scheme: dark;
${dark}
}
`;
}

function cssVarsBlock(palette) {
  const layers = [...LAYER_ORDER, OTHER_LAYER];
  return layers
    .map((layer) => `  --layer-${layer}: ${palette[layer]};`)
    .join("\n");
}

function buildThemeJs() {
  const funnel = JSON.stringify([OTHER_LAYER, ...[...LAYER_ORDER].reverse()]);
  return `/**
 * Palette A recolor for Allure 3 testing pyramid (colors-only).
 * Generated by zds dashboardTheme — no reshape / no geom observers.
 */
(function () {
  const FUNNEL_TOP_TO_BOTTOM = ${funnel};

  function findPyramidWidget(root) {
    return [...root.querySelectorAll('[class*="styles_widget"]')].find((el) =>
      /testing pyramid|пирамида тестирования/i.test(el.textContent || ""),
    );
  }

  function safeBBoxY(node) {
    try {
      return node.getBBox?.().y ?? 0;
    } catch {
      return 0;
    }
  }

  function normalizeLayer(raw) {
    const text = (raw || "").trim().toLowerCase();
    let best = null;
    for (const layer of FUNNEL_TOP_TO_BOTTOM) {
      if (text.startsWith(layer) && (!best || layer.length > best.length)) {
        best = layer;
      }
    }
    return best;
  }

  function layerLabelsFromWidget(widget) {
    const seen = new Set();
    const labels = [];
    widget.querySelectorAll("text, tspan").forEach((node) => {
      const match = (node.textContent || "").match(/Layer:\\s*(.+)/i);
      if (!match) return;
      const layer = normalizeLayer(match[1]);
      if (!layer || seen.has(layer)) return;
      seen.add(layer);
      const textEl = node.closest("text") || node;
      labels.push({ layer, y: safeBBoxY(textEl) });
    });
    return labels;
  }

  const EMPTY_LAYER_RE = /no tests|нет тестов/i;

  function emptyLayersFromWidget(widget) {
    const empty = new Set();
    widget.querySelectorAll("text").forEach((node) => {
      const text = node.textContent || "";
      const match = text.match(/Layer:\\s*(.+)/i);
      if (!match) return;
      const layer = normalizeLayer(match[1]);
      if (layer && EMPTY_LAYER_RE.test(text)) empty.add(layer);
    });
    return empty;
  }

  function pyramidShapes(svg) {
    return [...svg.querySelectorAll("path, polygon")]
      .filter((shape) => {
        const d = shape.getAttribute("d") || "";
        const points = shape.getAttribute("points") || "";
        return d.length > 16 || points.length > 8;
      })
      .map((shape) => ({ shape, y: safeBBoxY(shape) }))
      .sort((left, right) => left.y - right.y);
  }

  function pairShapesToLayers(shapeEntries, labels) {
    if (!shapeEntries.length) return [];
    if (shapeEntries.length === FUNNEL_TOP_TO_BOTTOM.length) {
      return [...FUNNEL_TOP_TO_BOTTOM];
    }
    if (labels.length === shapeEntries.length) {
      return [...labels].sort((a, b) => a.y - b.y).map((e) => e.layer);
    }
    if (labels.length > 0) {
      return shapeEntries.map((entry) => {
        let best = null;
        let bestDist = Infinity;
        for (const label of labels) {
          const dist = Math.abs(label.y - entry.y);
          if (dist < bestDist) {
            bestDist = dist;
            best = label.layer;
          }
        }
        return best;
      });
    }
    return shapeEntries.map(() => null);
  }

  function colorForLayer(layer) {
    if (!layer) return null;
    const cssVar = getComputedStyle(document.documentElement)
      .getPropertyValue("--layer-" + layer)
      .trim();
    return cssVar || null;
  }

  function setShapeFill(shape, layer) {
    const color = colorForLayer(layer);
    if (!color) return;
    shape.setAttribute("fill", color);
    shape.style.setProperty("fill", color, "important");
    shape.setAttribute("data-pyramid-layer", layer);
  }

  function setShapeHidden(shape, hidden) {
    if (hidden) shape.style.setProperty("display", "none", "important");
    else shape.style.removeProperty("display");
  }

  function setEmptyLabelVisibility(widget, emptyLayers) {
    widget.querySelectorAll("text").forEach((node) => {
      const match = (node.textContent || "").match(/Layer:\\s*(.+)/i);
      if (!match) return;
      const layer = normalizeLayer(match[1]);
      if (!layer) return;
      node.style.display = emptyLayers.has(layer) ? "none" : "";
    });
  }

  function paintPyramid(root) {
    const widget = findPyramidWidget(root || document);
    if (!widget) return false;
    const svg = widget.querySelector("svg");
    if (!svg) return false;
    const shapeEntries = pyramidShapes(svg);
    if (!shapeEntries.length) return false;

    const labels = layerLabelsFromWidget(widget);
    const layers = pairShapesToLayers(shapeEntries, labels);
    const emptyLayers = emptyLayersFromWidget(widget);
    setEmptyLabelVisibility(widget, emptyLayers);

    shapeEntries.forEach((entry, index) => {
      const layer = layers[index];
      const hidden = layer != null && emptyLayers.has(layer);
      setShapeHidden(entry.shape, hidden);
      if (!hidden && layer) setShapeFill(entry.shape, layer);
    });
    return true;
  }

  function schedulePaint() {
    paintPyramid();
    window.setTimeout(paintPyramid, 200);
    window.setTimeout(paintPyramid, 800);
    window.setTimeout(paintPyramid, 2000);
  }

  let paintQueued = false;
  function queuePaint() {
    if (paintQueued) return;
    paintQueued = true;
    requestAnimationFrame(function () {
      paintQueued = false;
      paintPyramid();
    });
  }

  new MutationObserver(queuePaint).observe(document.documentElement, {
    childList: true,
    subtree: true,
  });
  new MutationObserver(queuePaint).observe(document.documentElement, {
    attributes: true,
    attributeFilter: ["data-theme"],
  });
  window.addEventListener("storage", queuePaint);

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", schedulePaint);
  } else {
    schedulePaint();
  }
})();
`;
}

function patchHtmlFile({ filePath, cssHref, jsHref }) {
  if (!fs.existsSync(filePath)) {
    console.log(`apply-dashboard-theme: skip missing ${filePath}`);
    return;
  }

  let html = fs.readFileSync(filePath, "utf8");

  // Drop legacy dashboard-overrides inject if present.
  html = html
    .replace(/^\s*<link[^>]*data-dashboard-overrides[^>]*>\n?/gm, "")
    .replace(/^\s*<script[^>]*data-dashboard-overrides[^>]*><\/script>\n?/gm, "")
    .replace(/^\s*<link[^>]*data-an-dashboard-theme[^>]*>\n?/gm, "")
    .replace(/^\s*<script[^>]*data-an-dashboard-theme[^>]*><\/script>\n?/gm, "");

  if (html.includes(`href="${cssHref}"`) && html.includes(`src="${jsHref}"`)) {
    console.log(`apply-dashboard-theme: already patched ${filePath}`);
    return;
  }

  if (!html.includes("</head>")) {
    throw new Error(`apply-dashboard-theme: no </head> in ${filePath}`);
  }

  const inject = [
    `    <link rel="stylesheet" type="text/css" href="${cssHref}" ${DATA_ATTR}>`,
    `    <script src="${jsHref}" defer ${DATA_ATTR}></script>`,
  ].join("\n");

  html = html.replace("</head>", `${inject}\n</head>`);
  fs.writeFileSync(filePath, html);
  console.log(`apply-dashboard-theme: patched ${filePath}`);
}
