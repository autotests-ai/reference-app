/**
 * Intermediate Allure 3 report theme (after generate, before notifications).
 * CSS vars from ./pyramid-layer-colors.mjs; runtime JS reshapes zero-width funnel
 * bands to rounded tiers (Allure nivo collapses empty layers).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  PYRAMID_COLORS_DARK,
  PYRAMID_COLORS_LIGHT,
  PYRAMID_LAYERS,
} from "./pyramid-layer-colors.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const RUNTIME_JS = path.join(HERE, "dashboard-theme-runtime.js");

const TARGETS = ["awesome/index.html", "dashboard/index.html"];
const CSS_NAME = "an-dashboard-theme.css";
const JS_NAME = "an-dashboard-theme.js";
const DATA_ATTR = "data-an-dashboard-theme";
const OTHER_LAYER = "other";

/**
 * @param {{ reportRoot: string }} opts
 */
export function applyDashboardTheme({ reportRoot }) {
  fs.mkdirSync(reportRoot, { recursive: true });
  fs.writeFileSync(path.join(reportRoot, CSS_NAME), buildThemeCss(), "utf8");
  if (!fs.existsSync(RUNTIME_JS)) {
    throw new Error(`apply-dashboard-theme: missing runtime ${RUNTIME_JS}`);
  }
  fs.copyFileSync(RUNTIME_JS, path.join(reportRoot, JS_NAME));

  for (const rel of TARGETS) {
    patchHtmlFile({
      filePath: path.join(reportRoot, rel),
      cssHref: `../${CSS_NAME}`,
      jsHref: `../${JS_NAME}`,
    });
  }
}

function buildThemeCss() {
  const light = cssVarsBlock(PYRAMID_COLORS_LIGHT);
  const dark = cssVarsBlock(PYRAMID_COLORS_DARK);
  return `/* Generated by zds dashboardTheme from pyramid-layer-colors.mjs
 * (@allure-notifications/pyramid SSOT). Intermediate: generate → theme → notifications.
 * Runtime JS also reshapes collapsed empty funnel bands (see dashboard-theme-runtime.js).
 */
:root {
  color-scheme: light;
${light}
}

html[data-theme="light"] {
  color-scheme: light;
${light}
}

html[data-theme="dark"] {
  color-scheme: dark;
${dark}
}
`;
}

function cssVarsBlock(palette) {
  const layers = [...PYRAMID_LAYERS, OTHER_LAYER];
  return layers
    .map((layer) => `  --layer-${layer}: ${palette[layer]};`)
    .join("\n");
}

function patchHtmlFile({ filePath, cssHref, jsHref }) {
  if (!fs.existsSync(filePath)) {
    console.log(`apply-dashboard-theme: skip missing ${filePath}`);
    return;
  }

  let html = fs.readFileSync(filePath, "utf8");

  html = html
    .replace(/^\s*<link[^>]*data-dashboard-overrides[^>]*>\n?/gm, "")
    .replace(/^\s*<script[^>]*data-dashboard-overrides[^>]*><\/script>\n?/gm, "")
    .replace(/^\s*<link[^>]*data-an-dashboard-theme[^>]*>\n?/gm, "")
    .replace(/^\s*<script[^>]*data-an-dashboard-theme[^>]*><\/script>\n?/gm, "");

  if (html.includes(`href="${cssHref}"`) && html.includes(`src="${jsHref}"`)) {
    console.log(`apply-dashboard-theme: already patched ${filePath}`);
    return;
  }

  if (!html.includes("</head>")) {
    throw new Error(`apply-dashboard-theme: no </head> in ${filePath}`);
  }

  const inject = [
    `    <link rel="stylesheet" type="text/css" href="${cssHref}" ${DATA_ATTR}>`,
    `    <script src="${jsHref}" defer ${DATA_ATTR}></script>`,
  ].join("\n");

  html = html.replace("</head>", `${inject}\n</head>`);
  fs.writeFileSync(filePath, html);
  console.log(`apply-dashboard-theme: patched ${filePath}`);
}
